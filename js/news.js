function createNewsCard(item) {
  const card = document.createElement("a");
  card.classList.add("news-card");
  card.href = item.link;

  card.innerHTML = `
    <div class="news-card__image">
      <img src="${item.image}" alt="">
    </div>

    <p class="news-card__date text text--16">
      ${item.date}
    </p>

    <h3 class="news-card__title">
      ${item.title}
    </h3>

    <p class="news-card__text text text--18">
      ${item.text}
    </p>

    <span class="news-card__button">
      Читать
    </span>
  `;

  return card;
}

/* Главная страница: слайдер новостей */

const newsSlider = document.querySelector("#newsSlider");
const newsPrev = document.querySelector("#newsPrev");
const newsNext = document.querySelector("#newsNext");

function renderNewsSlider() {
  if (!newsSlider) return;

  newsSlider.innerHTML = "";

  newsList.forEach((item) => {
    newsSlider.appendChild(createNewsCard(item));
  });
}

function scrollNews(direction) {
  if (!newsSlider) return;

  const card = newsSlider.querySelector(".news-card");

  if (!card) return;

  const gap = 24;
  const scrollSize = card.offsetWidth + gap;

  newsSlider.scrollBy({
    left: direction * scrollSize,
    behavior: "smooth"
  });
}

if (newsPrev && newsNext) {
  newsPrev.addEventListener("click", () => scrollNews(-1));
  newsNext.addEventListener("click", () => scrollNews(1));
}

renderNewsSlider();

/* Страница news.html: сетка + пагинация */

const newsPageGrid = document.querySelector("#newsPageGrid");
const newsPageNumbers = document.querySelector("#newsPageNumbers");
const newsPagePrev = document.querySelector("#newsPagePrev");
const newsPageNext = document.querySelector("#newsPageNext");

const newsPerPage = 6;
let currentNewsPage = 1;

function getTotalNewsPages() {
  return Math.ceil(newsList.length / newsPerPage);
}

function renderNewsPage() {
  if (!newsPageGrid || !newsPageNumbers) return;

  const start = (currentNewsPage - 1) * newsPerPage;
  const end = start + newsPerPage;
  const pageItems = newsList.slice(start, end);

  newsPageGrid.innerHTML = "";

  pageItems.forEach((item) => {
    newsPageGrid.appendChild(createNewsCard(item));
  });

  renderNewsPagination();
}

function renderNewsPagination() {
  const totalPages = getTotalNewsPages();

  newsPageNumbers.innerHTML = "";

  for (let i = 1; i <= totalPages; i++) {
    if (totalPages > 5 && i > 2 && i < totalPages) {
      if (i === 3) {
        const dots = document.createElement("span");
        dots.classList.add("news-page__page-dots");
        dots.textContent = "...";
        newsPageNumbers.appendChild(dots);
      }

      continue;
    }

    const button = document.createElement("button");
    button.classList.add("news-page__page");
    button.type = "button";
    button.textContent = i;

    if (i === currentNewsPage) {
      button.classList.add("news-page__page--active");
    }

    button.addEventListener("click", () => {
      currentNewsPage = i;
      renderNewsPage();
    });

    newsPageNumbers.appendChild(button);
  }
}

if (newsPagePrev && newsPageNext) {
  newsPagePrev.addEventListener("click", () => {
    currentNewsPage--;

    if (currentNewsPage < 1) {
      currentNewsPage = getTotalNewsPages();
    }

    renderNewsPage();
  });

  newsPageNext.addEventListener("click", () => {
    currentNewsPage++;

    if (currentNewsPage > getTotalNewsPages()) {
      currentNewsPage = 1;
    }

    renderNewsPage();
  });
}

renderNewsPage();